// Get translation by dot notation key
function getTranslation(keyPath, lang = 'en') {
  const keys = keyPath.split('.');
  let value = translations[lang] || translations['en'];
  
  for (let key of keys) {
    value = value?.[key];
    if (!value) return keyPath;
  }
  return value;
}

// Enhanced Language Manager Class with Dynamic Translation
class LanguageManager {
  constructor() {
    this.currentLanguage = localStorage.getItem('supplierLanguage') || 'en';
  }

  init() {
    this.setupLanguageButtons();
    this.setActiveLanguageButton();
    this.translatePageContent(this.currentLanguage);
  }

  setupLanguageButtons() {
    const buttons = document.querySelectorAll('.language-btn');
    buttons.forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
          e.stopPropagation();
        const lang = btn.dataset.lang;
        this.setLanguage(lang);
        this.setActiveLanguageButton();
        this.translatePageContent(lang);
      });
    });
  }

  setActiveLanguageButton() {
    const buttons = document.querySelectorAll('.language-btn');
    const currentLang = this.currentLanguage;
    buttons.forEach(btn => {
      if (btn.dataset.lang === currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLanguage = lang;
      localStorage.setItem('supplierLanguage', lang);
      document.documentElement.lang = lang;
    }
  }

  getLanguage() {
    return this.currentLanguage;
  }

  translate(key) {
    return getTranslation(key, this.currentLanguage);
  }

  translatePageContent(lang) {
    // Translate all elements with data-translate attribute
    const translatableElements = document.querySelectorAll('[data-translate]');
    translatableElements.forEach(el => {
      const keyPath = el.getAttribute('data-translate');
      const translatedText = this.translate(keyPath);
      if (translatedText) {
        el.textContent = translatedText;
      }
    });

    // Translate badge pills with special handling for "label: value" format
    const badgePills = document.querySelectorAll('.badge-pill');
    badgePills.forEach(badge => {
      // Check if the badge has a stored original value (label + colon + value)
      const text = badge.textContent.trim();
      const colonIndex = text.indexOf(':');
      
      if (colonIndex > -1) {
        const label = text.substring(0, colonIndex).trim();
        const value = text.substring(colonIndex + 1).trim();
        let translatedLabel = label;
        
        if (label === 'Warehouses') translatedLabel = this.translate('badges.warehouses');
        else if (label === 'Service Areas') translatedLabel = this.translate('badges.serviceAreas');
        else if (label === 'Products') translatedLabel = this.translate('badges.products');
        else if (label === 'Earnings') translatedLabel = this.translate('badges.earnings');
        else if (label === 'Verified') translatedLabel = this.translate('badges.verified') || label;
        
        badge.textContent = value ? translatedLabel + ': ' + value : translatedLabel;
      }
    });
  }
}

// Initialize language manager when DOM is ready
let languageManager;

function initLanguageManager() {
  languageManager = new LanguageManager();
  
  // Make globally accessible
  window.translations = translations;
  window.getTranslation = getTranslation;
  window.languageManager = languageManager;
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLanguageManager);
} else {
  initLanguageManager();
}
